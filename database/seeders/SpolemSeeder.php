<?php

namespace Database\Seeders;

use App\Actions\Teams\CreateTeam;
use App\Enums\UserRole;
use App\Models\Organization;
use App\Models\ShopBranch;
use App\Models\ShopHeadquarter;
use App\Models\User;
use App\Models\WarehouseHeadquarter;
use Illuminate\Database\Seeder;

/**
 * The second organization for trying the trade module: Społem Jasło Sp. z o.o. with a main shop (headquarters), a main
 * warehouse (headquarters) and two shops (branches of the main shop), each with its manager. Password of all accounts: qwer1234.
 *
 * Accounts (spolem_{role}@test.pl): spolem_organization, spolem_shop_owner (the main shop), spolem_warehouse_owner
 * (the main warehouse), spolem_shop_leader_1 (ul. Kościuszki), spolem_shop_leader_2 (ul. Jana Pawła II), and three workers in each shop: spolem_shop_worker_{shop 1|2}_{1..3}.
 *
 * It uses what already exists (by NIP) and creates what is missing, so it can be run again. Barcodes are generated by the
 * models ("created" event), so model events must not be disabled.
 */
class SpolemSeeder extends Seeder
{
    private const NIP = '6852335266';

    private const NAME = 'Społem Jasło Sp. z o.o.';

    private int $phone = 100;

    public function run(): void
    {
        // the accounts have a password that is written in this file: only on a development machine
        if (! app()->environment(['local', 'testing'])) {
            $this->command?->warn('SpolemSeeder pominięty: konta z jawnym hasłem tworzymy tylko w środowisku local lub testing.');

            return;
        }

        $kosciuszki = ['street' => 'Tadeusza Kościuszki', 'building_number' => '45', 'postal_code' => '38-200', 'city' => 'Jasło', 'country' => 'PL'];
        $jpii = ['street' => 'Jana Pawła II', 'building_number' => '28', 'postal_code' => '38-200', 'city' => 'Jasło', 'country' => 'PL'];

        $organization = Organization::firstOrCreate(['NIP' => self::NIP], ['name' => self::NAME, 'email' => 'spolem_organizacja@test.pl', ...$kosciuszki]);

        $shop = ShopHeadquarter::firstOrCreate(
            ['organization_id' => $organization->id, 'name' => 'Społem Jasło - sklep główny'],
            ['email' => 'spolem_sklep@test.pl', 'NIP' => self::NIP, ...$kosciuszki],
        );
        $warehouse = WarehouseHeadquarter::firstOrCreate(
            ['organization_id' => $organization->id, 'name' => 'Społem Jasło - hurtownia główna'],
            ['email' => 'spolem_hurtownia@test.pl', 'NIP' => self::NIP, ...$kosciuszki],
        );

        $shopOne = ShopBranch::firstOrCreate(
            ['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id, 'name' => 'Społem Jasło - sklep Kościuszki'],
            ['email' => 'spolem_sklep_1@test.pl', 'NIP' => self::NIP, ...$kosciuszki],
        );
        $shopTwo = ShopBranch::firstOrCreate(
            ['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id, 'name' => 'Społem Jasło - sklep Jana Pawła II'],
            ['email' => 'spolem_sklep_2@test.pl', 'NIP' => self::NIP, ...$jpii],
        );

        $this->user('spolem_organization@test.pl', 'Społem właściciel organizacji', UserRole::ORGANIZATION_OWNER, ['organization_id' => $organization->id]);
        $this->user('spolem_shop_owner@test.pl', 'Społem kierownik sklepu głównego', UserRole::SHOP_OWNER, ['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id]);
        $this->user('spolem_warehouse_owner@test.pl', 'Społem kierownik hurtowni głównej', UserRole::WAREHOUSE_OWNER, ['organization_id' => $organization->id, 'warehouse_headquarter_id' => $warehouse->id]);
        $this->user('spolem_shop_leader_1@test.pl', 'Społem kierownik sklepu Kościuszki', UserRole::SHOP_LEADER, ['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id, 'shop_branch_id' => $shopOne->id]);
        $this->user('spolem_shop_leader_2@test.pl', 'Społem kierownik sklepu Jana Pawła II', UserRole::SHOP_LEADER, ['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id, 'shop_branch_id' => $shopTwo->id]);

        // three workers in each shop
        foreach ([1 => $shopOne, 2 => $shopTwo] as $number => $branch) {
            foreach (range(1, 3) as $worker) {
                $this->user("spolem_shop_worker_{$number}_{$worker}@test.pl", "Społem pracownik sklepu {$number}/{$worker}", UserRole::SHOP_WORKER, ['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id, 'shop_branch_id' => $branch->id]);
            }
        }
    }

    /**
     * @param  array<string, mixed>  $links
     */
    private function user(string $email, string $name, UserRole $role, array $links): void
    {
        if (User::where('email', $email)->exists()) {
            return;
        }

        $user = User::create([
            'name' => $name,
            'email' => $email,
            'phone' => $this->nextPhone(),
            'password' => 'qwer1234', // hashed by the "hashed" cast
            'role' => $role,
            ...$links,
        ]);

        $user->forceFill(['email_verified_at' => now()])->save();

        app(CreateTeam::class)->handle($user, $user->name."'s Team", isPersonal: true);
    }

    /** Phone numbers +48 12 000 01 01, 02, ... (the taken ones are skipped). */
    private function nextPhone(): string
    {
        do {
            $phone = '+4812000'.str_pad((string) ++$this->phone, 4, '0', STR_PAD_LEFT);
        } while (User::where('phone', $phone)->exists());

        return $phone;
    }
}
