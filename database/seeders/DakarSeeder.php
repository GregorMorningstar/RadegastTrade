<?php

namespace Database\Seeders;

use App\Actions\Teams\CreateTeam;
use App\Enums\HeadquarterType;
use App\Enums\UnitLevel;
use App\Enums\UnitPosition;
use App\Enums\UserRole;
use App\Models\Organization;
use App\Models\ShopBranch;
use App\Models\ShopHeadquarter;
use App\Models\User;
use App\Models\WarehouseBranch;
use App\Models\WarehouseHeadquarter;
use App\Repositories\Contracts\UnitMembershipRepositoryInterface;
use Illuminate\Database\Seeder;

/**
 * The DAKAR organization with its owner, its warehouse and its shop: in each a headquarters manager, a branch manager
 * (leader) and three workers, and the platform accounts. Password of all accounts: qwer1234.
 *
 * Accounts (dakar_{role}@test.pl):
 *  - the platform: dakar_admin@test.pl (administrator, invites organizations), dakar_manager@test.pl, dakar_employee@test.pl
 *  - the organization owner: dakar_organization@test.pl (invites the main headquarters)
 *  - the managers: dakar_warehouse_owner@test.pl, dakar_warehouse_leader@test.pl, dakar_shop_owner@test.pl, dakar_shop_leader@test.pl
 *  - the workers, dakar_{role}_{1..3}@test.pl: dakar_warehouse_worker_1@test.pl ... dakar_shop_worker_3@test.pl
 *
 * It uses the existing DAKAR organization (NIP 6851047393) and its headquarters and branches when they exist, and
 * creates what is missing, so it can be run on the database already in use as well as on a fresh one.
 * It also puts the first hand-made DAKAR accounts in the positions their names say (see repairHandMadeAccounts).
 * Barcodes are generated by the models ("created" event), so model events must not be disabled.
 */
class DakarSeeder extends Seeder
{
    private const NIP = '6851047393';

    private const NAME = 'FIRMA HANDLOWA "DAKAR" PIOTR SZOSTAK, MARCIN WÓJCIK - SPÓŁKA JAWNA';

    private int $phone = 0;

    public function run(): void
    {
        // the accounts have a password that is written in this file: never on a server that is not a development machine
        // (a whitelist, not "everything but production": a staging host is reachable too)
        if (! app()->environment(['local', 'testing'])) {
            $this->command?->warn('DakarSeeder pominięty: konta z jawnym hasłem tworzymy tylko w środowisku local lub testing.');

            return;
        }

        $organization = Organization::firstOrCreate(['NIP' => self::NIP], [
            'name' => self::NAME,
            'email' => 'organizacion_dakar@test.pl',
            'street' => 'ALOJZEGO METZGERA',
            'building_number' => '4',
            'postal_code' => '38-200',
            'city' => 'JASŁO',
            'country' => 'PL',
        ]);

        // the platform accounts (no organization) and the owner of the organization
        $this->user('dakar_admin@test.pl', 'Dakar administrator', UserRole::Admin, []);
        $this->user('dakar_manager@test.pl', 'Dakar manager platformy', UserRole::Manager, []);
        $this->user('dakar_employee@test.pl', 'Dakar pracownik platformy', UserRole::Employee, []);
        $this->user('dakar_organization@test.pl', 'Dakar właściciel organizacji', UserRole::ORGANIZATION_OWNER, ['organization_id' => $organization->id]);

        $address = [
            'NIP' => self::NIP,
            'street' => 'ALOJZEGO METZGERA',
            'building_number' => '4',
            'postal_code' => '38-200',
            'city' => 'JASŁO',
            'country' => 'PL',
        ];

        $warehouse = WarehouseHeadquarter::where('organization_id', $organization->id)->orderBy('id')->first()
            ?? WarehouseHeadquarter::create(['organization_id' => $organization->id, 'name' => 'DAKAR - hurtownia główna', 'email' => 'dakar_hurtownia@test.pl', ...$address]);
        $warehouseBranch = WarehouseBranch::where('warehouse_headquarter_id', $warehouse->id)->orderBy('id')->first()
            ?? WarehouseBranch::create(['organization_id' => $organization->id, 'warehouse_headquarter_id' => $warehouse->id, 'name' => 'DAKAR - magazyn 1', ...$address]);

        $shop = ShopHeadquarter::where('organization_id', $organization->id)->orderBy('id')->first()
            ?? ShopHeadquarter::create(['organization_id' => $organization->id, 'name' => 'DAKAR - sklep główny', 'email' => 'dakar_sklep@test.pl', ...$address]);
        $shopBranch = ShopBranch::where('shop_headquarter_id', $shop->id)->orderBy('id')->first()
            ?? ShopBranch::create(['organization_id' => $organization->id, 'shop_headquarter_id' => $shop->id, 'name' => 'DAKAR - sklep 1', ...$address]);

        $this->staff($organization, HeadquarterType::Warehouse, $warehouse->id, $warehouseBranch->id, 'hurtowni');
        $this->staff($organization, HeadquarterType::Shop, $shop->id, $shopBranch->id, 'sklepu');

        $this->repairHandMadeAccounts($organization, $warehouse->id, $warehouseBranch->id);
    }

    /**
     * A manager of the headquarters, a manager (leader) of the branch and three workers of the branch.
     */
    private function staff(Organization $organization, HeadquarterType $type, int $headquarterId, int $branchId, string $noun): void
    {
        $group = ['organization_id' => $organization->id, $type->headquarterColumn() => $headquarterId];
        $branch = [...$group, $type->branchColumn() => $branchId];

        $this->user("dakar_{$type->ownerRole()->value}@test.pl", "Dakar kierownik siedziby {$noun}", $type->ownerRole(), $group);
        $this->user("dakar_{$type->leaderRole()->value}@test.pl", "Dakar kierownik placówki {$noun}", $type->leaderRole(), $branch);

        foreach (range(1, 3) as $number) {
            $this->user("dakar_{$type->workerRole()->value}_{$number}@test.pl", "Dakar pracownik {$noun} {$number}", $type->workerRole(), $branch);
        }
    }

    /**
     * The accounts made by hand while testing: dakar1@o2.pl founded the DAKAR warehouse headquarters (and was
     * later left without it, as a worker), and "dakar pracownik hurtowni 1" is named a worker but holds the
     * headquarters manager role without a headquarters. Both are put where their names say: dakar1 manages the
     * headquarters, the other one works in the branch. Only accounts that have no unit are touched.
     */
    private function repairHandMadeAccounts(Organization $organization, int $warehouseId, int $warehouseBranchId): void
    {
        $memberships = app(UnitMembershipRepositoryInterface::class);

        $founder = User::where('email', 'dakar1@o2.pl')->where('organization_id', $organization->id)->first();
        $worker = User::where('email', 'dakar_ph1@test.pl')->where('organization_id', $organization->id)->first();

        if ($founder !== null && $memberships->forUser($founder) === null) {
            $memberships->place($founder, HeadquarterType::Warehouse, UnitLevel::Headquarters, $warehouseId, UnitPosition::Manager);
        }

        if ($worker !== null && $memberships->forUser($worker) === null) {
            $memberships->place($worker, HeadquarterType::Warehouse, UnitLevel::Branch, $warehouseBranchId, UnitPosition::Worker);
        }
    }

    /**
     * @param  array<string, mixed>  $links
     */
    private function user(string $email, string $name, UserRole $role, array $links): void
    {
        if (User::where('email', $email)->exists()) {
            return;
        }

        $user = User::create([
            'name' => $name,
            'email' => $email,
            'phone' => $this->nextPhone(),
            'password' => 'qwer1234', // hashed by the "hashed" cast
            'role' => $role,
            ...$links,
        ]);

        $user->forceFill(['email_verified_at' => now()])->save();

        app(CreateTeam::class)->handle($user, $user->name."'s Team", isPersonal: true);
    }

    /**
     * Phone numbers +48 71 000 00 01, 02, ... (the same ones on every run, skipping the taken ones).
     */
    private function nextPhone(): string
    {
        do {
            $phone = '+4871000'.str_pad((string) ++$this->phone, 4, '0', STR_PAD_LEFT);
        } while (User::where('phone', $phone)->exists());

        return $phone;
    }
}
